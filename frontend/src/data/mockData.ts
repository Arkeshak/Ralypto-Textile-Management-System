// Helper to generate dynamic relative dates so today always has realistic transactions
export const getRelativeDate = (daysAgo: number, hoursOffset: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  if (hoursOffset) {
    d.setHours(d.getHours() - hoursOffset);
  }
  return d.toISOString();
};

