export const generateDemoTrend = () => {
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const trend = [];
  const today = new Date();

  const sampleValues = [
    { sales: 74200, profit: 34800 },
    { sales: 68500, profit: 31200 },
    { sales: 92400, profit: 42100 },
    { sales: 81300, profit: 38700 },
    { sales: 96500, profit: 45200 },
    { sales: 112000, profit: 54100 },
    { sales: 84500, profit: 39650 }, // Today!
  ];

  for (let i = 6; i >= 0; i--) {
    const d = new Date();
    d.setDate(today.getDate() - i);
    const dayLabel = `${days[d.getDay()]} ${d.getDate()}`;
    const val = sampleValues[6 - i];
    trend.push({
      date: dayLabel,
      sales: val.sales,
      profit: val.profit,
      transactions: Math.round(val.sales / 2650),
    });
  }

  return trend;
};

